-- PAP Berdua — jalankan SEKALI di Supabase: SQL Editor → New query → tempel → Run
-- Membuat tabel foto PAP + tabel lokasi terakhir, hanya bisa diakses akun yang login.

create table if not exists public.pap (
  id bigint generated always as identity primary key,
  sender text not null,
  photo text not null,
  caption text,
  lat double precision,
  lng double precision,
  created_at timestamptz not null default now()
);

create table if not exists public.lokasi (
  sender text primary key,
  lat double precision not null,
  lng double precision not null,
  updated_at timestamptz not null default now()
);

alter table public.pap enable row level security;
alter table public.lokasi enable row level security;

drop policy if exists "akun login akses penuh pap" on public.pap;
create policy "akun login akses penuh pap" on public.pap
  for all to authenticated using (true) with check (true);

drop policy if exists "akun login akses penuh lokasi" on public.lokasi;
create policy "akun login akses penuh lokasi" on public.lokasi
  for all to authenticated using (true) with check (true);

-- Tabel sinyal cepat (hati / cium / semangat / pesan kilat) — fitur aplikasi v1.3+
create table if not exists public.sinyal (
  id bigint generated always as identity primary key,
  sender text not null,
  kind text not null,
  isi text,
  created_at timestamptz not null default now()
);

alter table public.sinyal enable row level security;

drop policy if exists "akun login akses penuh sinyal" on public.sinyal;
create policy "akun login akses penuh sinyal" on public.sinyal
  for all to authenticated using (true) with check (true);

-- Kolom baterai (%) di tabel lokasi — fitur "baterai & terakhir aktif pasangan" (aplikasi v1.7+)
alter table public.lokasi add column if not exists baterai int;

-- Tempat penting — fitur "notif sampai tujuan" (aplikasi v1.8+)
create table if not exists public.tempat (
  id bigint generated by default as identity primary key,
  nama text not null,
  lat double precision not null,
  lng double precision not null,
  radius int not null default 200,
  dibuat_oleh text not null default 'bobby',
  created_at timestamptz not null default now()
);
alter table public.tempat enable row level security;
drop policy if exists "akun login akses penuh tempat" on public.tempat;
create policy "akun login akses penuh tempat" on public.tempat
  for all to authenticated using (true) with check (true);

-- Jejak lokasi — fitur "jejak lokasi hari ini" (aplikasi v1.8+)
create table if not exists public.jejak (
  id bigint generated by default as identity primary key,
  sender text not null,
  lat double precision not null,
  lng double precision not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_jejak_sender_waktu on public.jejak (sender, created_at);
alter table public.jejak enable row level security;
drop policy if exists "akun login akses penuh jejak" on public.jejak;
create policy "akun login akses penuh jejak" on public.jejak
  for all to authenticated using (true) with check (true);

-- Video PAP (aplikasi v1.9+): jenis='foto'|'video', video=base64 MP4 (photo tetap cover/foto), efek=nama filter
alter table public.pap add column if not exists jenis text not null default 'foto';
alter table public.pap add column if not exists video text;
alter table public.pap add column if not exists efek text;

-- Paket Kejujuran (aplikasi v2.0+): sumber PAP ('langsung'|'galeri'), tanda sudah dilihat,
-- penanda lokasi palsu (Fake GPS), dan jurnal transparansi berdua
alter table public.pap add column if not exists sumber text;
alter table public.pap add column if not exists dilihat_pada timestamptz;
alter table public.lokasi add column if not exists palsu boolean not null default false;

create table if not exists public.jurnal (
  id bigint generated by default as identity primary key,
  siapa text not null,
  peristiwa text not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_jurnal_waktu on public.jurnal (created_at desc);
alter table public.jurnal enable row level security;
drop policy if exists "akun login akses jurnal" on public.jurnal;
create policy "akun login akses jurnal" on public.jurnal
  for all to authenticated using (true) with check (true);

-- v7: Realtime — agar server mendorong PAP/sinyal baru ke aplikasi dalam ±1 detik
-- (dipakai aplikasi Android v2.5+ & web; aman dijalankan berulang)
do $$
begin
  begin
    alter publication supabase_realtime add table public.pap;
  exception when duplicate_object then null;
  end;
  begin
    alter publication supabase_realtime add table public.sinyal;
  exception when duplicate_object then null;
  end;
end $$;

